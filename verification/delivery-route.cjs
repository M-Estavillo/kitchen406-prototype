const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const courierQuotation=require('../courier-quotation.cjs');

(async()=>{
 const date=offset=>new Date(Date.now()+offset*86400000).toISOString().slice(0,10);
 const dates=[2,9,16,23].map(date);
 const demoAddress='1 Demo Bakery Lane, Poblacion, Liloan, 6002, Philippines';
 const demo=courierQuotation.demoQuotation;
 assert.equal(demo({address:demoAddress,dates:dates.slice(0,1)}).quotations[0].fee,85);
 const subscription=demo({address:demoAddress,dates});
 assert.deepEqual(subscription.quotations.map(quote=>quote.date),dates);
 const token=courierQuotation.checkoutQuote(demoAddress,subscription.quotations);
 assert.equal(courierQuotation.validCheckoutQuote(token,demoAddress,dates,[8500,8500,8500,8500],Date.now()),true);
 assert.equal(courierQuotation.validCheckoutQuote(token,demoAddress,dates,[0,8500,8500,8500],Date.now()),false);
 assert.equal(demo({address:'3 Demo Harbor Lane, Poblacion, Danao, 6004, Philippines',dates}).status,'outside');
 assert.equal(demo({address:'Unknown address',dates}).status,'invalid');
 const env={GOOGLE_MAPS_SERVER_KEY:'maps',K406_BAKERY_ORIGIN:'Bakery',K406_COURIER_PICKUP_TIME:'09:00',
  LALAMOVE_API_KEY:'mock',LALAMOVE_API_SECRET:'mock',LALAMOVE_SERVICE_TYPE:'MOTORCYCLE'};
 const calls=new Map();
 let distance=10000,location='valid',failure='retry';
 const courier=courierQuotation(env,async(url,options)=>{
  if(String(url).includes('/geocode/')){
   const isDestination=url.searchParams.get('address')!=='Bakery';
   if(isDestination&&location==='missing')return Response.json({status:'ZERO_RESULTS'});
   if(isDestination&&location==='error')return Response.json({status:'OVER_QUERY_LIMIT'});
   return Response.json({status:'OK',results:[{formatted_address:'Cebu fixture',geometry:{location_type:'ROOFTOP',location:{lat:10,lng:123}}}]});
  }
  if(String(url).includes('computeRoutes'))return Response.json({routes:distance===null?[]:[{distanceMeters:distance}]});
  assert.equal(new URL(url).pathname,'/v3/quotations');
  assert.equal(options.headers.Market,'PH');
  const [key,time,signature]=options.headers.Authorization.slice(5).split(':');
  const input=JSON.parse(options.body).data;
  assert.equal(input.stops.length,2);
  assert.equal(key,'mock');
  assert.equal(signature,require('node:crypto').createHmac('sha256','mock').update([time,'POST','/v3/quotations','',options.body].join('\r\n')).digest('hex'));
  const cycle=dates.indexOf(input.scheduleAt.slice(0,10));
  calls.set(cycle,(calls.get(cycle)||0)+1);
  if(failure==='definitive')return new Response(null,{status:422});
  if(failure==='retry'&&cycle===1&&calls.get(cycle)<3)return new Response(null,{status:503});
  return Response.json({data:{quotationId:'test-'+cycle,expiresAt:new Date(Date.now()+300000).toISOString(),priceBreakdown:{currency:'PHP',total:(100+cycle)+'.50'}}});
 });
 const input={address:'Cebu City',dates};
 assert.deepEqual((await courier.check(input)).quotations.map(row=>row.fee),[100.5,101.5,102.5,103.5]);
 assert.deepEqual([...calls],[ [0,1],[1,3],[2,1],[3,1] ]);
 calls.clear();
 distance=10001;
 assert.equal((await courier.check(input)).status,'outside');
 assert.equal(calls.size,0);
 distance=null;
 assert.equal((await courier.check(input)).status,'unreachable');
 distance=9999;
 location='missing';
 assert.equal((await courier.check(input)).status,'invalid');
 location='error';
 assert.equal((await courier.check(input)).status,'error');
 location='valid';
 assert.equal((await courier.check({address:input.address,dates:[date(35)]})).status,'schedule-unavailable');
 failure='definitive';
 assert.equal((await courier.check(input)).status,'quote-unavailable');
 assert.equal(calls.get(0),1);
 assert.equal((await courierQuotation({}).check(input)).status,'unconfigured');

 const selected={address_id:'home',add_line_1:'Demo street',city:'Cebu City',postal_code:'6000'};
 const draft={method:'delivery',date:dates[0],service:'ok'};
 const requests=[];
 const commerce={address:()=>selected,addressValid:()=>true,state:{draft},render(){}};
 const context={K406:{commerce},K406_MAPS_CONFIG:{courierProvider:true},queueMicrotask,
  fetch:(_url,request)=>new Promise(resolve=>requests.push({resolve,payload:JSON.parse(request.body)}))};
 vm.runInNewContext(fs.readFileSync('app/delivery-route.js','utf8'),context);
 const route=commerce.deliveryRoute;
 const first=route.check();
 assert.equal(route.status(),'loading');
 draft.date=dates[1];
 const second=route.check();
 assert.deepEqual(requests[1].payload.dates,[dates[1]]);
 requests[1].resolve(Response.json({status:'ok',quotations:[{fee:120,expiresAt:new Date(Date.now()+300000).toISOString()}]}));
 await second;
 requests[0].resolve(Response.json({status:'outside'}));
 await first;
 assert.equal(route.quotations()[0].fee,120);
 draft.method='pickup';
 assert.equal(route.quotations().length,0);
 route.reset();
 draft.method='delivery';
 const expired=route.check();
 requests.at(-1).resolve(Response.json({status:'ok',quotations:[{fee:10,expiresAt:new Date(0).toISOString()}]}));
 await expired;
 assert.equal(route.status(),'expired');
 assert.equal(route.quotations().length,0);
 context.K406_MAPS_CONFIG.courierProvider=false;
 assert.equal(route.status(),'unconfigured');
 assert.equal(route.eligible(),false);
 assert.equal(route.quotations().length,0);
 console.log('PASS courier provider stand-ins, distance boundary, partial retries, provider failures, stale responses, expiry and unconfigured courier behavior');
})().catch(error=>{console.error(error);process.exitCode=1;});
